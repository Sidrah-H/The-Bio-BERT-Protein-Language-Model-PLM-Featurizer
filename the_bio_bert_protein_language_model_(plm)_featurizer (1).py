pd.set_option('display.max_colwidth', None)

adme_records = []
top_candidates = top_novel_per_target.drop_duplicates(subset=["SMILES"])

for _, row in top_candidates.iterrows():
    mol = Chem.MolFromSmiles(row["SMILES"])
    if not mol:
        continue

    mw = Descriptors.MolWt(mol)
    logp = Descriptors.MolLogP(mol)
    hbd = Lipinski.NumHDonors(mol)
    hba = Lipinski.NumHAcceptors(mol)
    tpsa = Descriptors.TPSA(mol)
    rot_bonds = Lipinski.NumRotatableBonds(mol)
    heavy_atoms = mol.GetNumHeavyAtoms()
    num_aromatic = rdMolDescriptors.CalcNumAromaticRings(mol)

    # 1. Lipinski's Rule of Five Violations
    violations = sum([mw > 500, logp > 5, hbd > 5, hba > 10])

    # 2. ESOL Aqueous Solubility Estimation (LogS) via Delaney Equation
    aromatic_prop = num_aromatic / heavy_atoms if heavy_atoms > 0 else 0
    logs = 0.16 - (0.63 * logp) - (0.0062 * mw) + (0.066 * rot_bonds) - (0.74 * aromatic_prop)

    if logs > -2: sol_class = "Soluble"
    elif logs > -4: sol_class = "Moderately soluble"
    elif logs > -6: sol_class = "Poorly soluble"
    else: sol_class = "Insoluble"

    # 3. Gastrointestinal (GI) Absorption Heuristic
    gi_abs = "High" if tpsa < 140 and rot_bonds <= 10 else "Low"

    # 4. Blood-Brain Barrier (BBB) Permeation Heuristic
    bbb_perm = "Yes" if tpsa < 90 and 1.0 <= logp <= 4.5 and mw <= 400 else "No"

    # 5. Bioavailability Status Assessment
    bio_status = "Good (0.55)" if violations == 0 and gi_abs == "High" else ("Moderate (0.55)" if violations == 1 else "Low (0.11)")

    adme_records.append({
        "Target_Gene": row["Target_Gene"],
        "Ligand_Name": row["Ligand_Name"],
        "SMILES": row["SMILES"],
        "MW": round(mw, 2),
        "LogP": round(logp, 2),
        "Solubility (LogS)": round(logs, 2),
        "Solubility Class": sol_class,
        "GI Absorption": gi_abs,
        "BBB Permeant": bbb_perm,
        "Lipinski Violations": violations,
        "Bioavailability Status": bio_status
    })

df_adme = pd.DataFrame(adme_records)
print(f"\n[✓] Successfully generated SwissADME profile for {len(df_adme)} candidates:\n")
